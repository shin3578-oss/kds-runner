#!/usr/bin/env bash
# ==========================================================
# ステップの結果を公開ログにどう出すかを、ここに一本化する。
#   使い方: bash ../runner/emit.sh <スクリプトの終了コード> <ログファイル>
#
# ・成功した回は**中身を出さない**（何行あったかだけ）。
#   このリポジトリは公開なので、うまくいった日の詳細を世界に見せる必要がない。
# ・失敗した回だけ mask.py を通して出す。原因を追うのに要るため。
# ・終了コードはそのまま返す（失敗をジョブの失敗として伝える）。
# ==========================================================
set -u
RC="${1:-1}"
LOG="${2:-/dev/null}"
LINES=$(wc -l < "$LOG" 2>/dev/null || echo 0)

if [ "$RC" -eq 0 ]; then
  echo "✅ 正常終了（出力 ${LINES} 行。公開リポジトリなので中身は出しません）"
  echo "--- 最後の3行（マスク済み） ---"
  tail -n 3 "$LOG" | python "$(dirname "$0")/mask.py"
else
  echo "❌ 終了コード ${RC} で失敗。マスク済みログを出します（出力 ${LINES} 行）"
  python "$(dirname "$0")/mask.py" < "$LOG"
fi
exit "$RC"
